"""Compare BGT labelling between areas, to catch municipalities with different conventions before mixing them.

For each area:
- the share of road surface (wegdeel) per BGT function
- fietsstraten from OpenStreetMap (cyclestreet=yes / bicycle_road=yes) and which BGT function the polygons
  under them have, which shows whether a municipality maps them as carriageway or as bike path

OSM results are cached in data/nl/<area>_osm_bikestreets.json. Writes a Markdown report.
"""
import argparse
import json
import os
import pickle
import time

import httpx
import numpy as np
import pyproj
import shapely

from areas import AREAS, area_dir

OVERPASS = "https://overpass-api.de/api/interpreter"
CRS = "EPSG:28992"


def bike_streets(area: str, folder: str) -> list[list[tuple[float, float]]]:
    """OSM fietsstraat centrelines in the area, as lon/lat point lists (cached in the area's folder)."""
    path = f"{folder}/{area}_osm_bikestreets.json"
    if os.path.exists(path):
        with open(path) as file:
            return json.load(file)
    west, south, east, north = AREAS[area]
    box = f"{south},{west},{north},{east}"
    query = f'[out:json][timeout:90];(way["cyclestreet"="yes"]({box});way["bicycle_road"="yes"]({box}););out geom;'
    for attempt in range(6):  # the public Overpass server is often busy (429/502/504)
        try:
            response = httpx.post(OVERPASS, data={"data": query}, timeout=120,
                                  headers={"User-Agent": "road-centerline-annotator/0.1"})
            response.raise_for_status()
            break
        except httpx.HTTPError:
            if attempt == 5:
                raise
            time.sleep(10 * 2 ** attempt)
    lines = [[(p["lon"], p["lat"]) for p in way["geometry"]] for way in response.json()["elements"]
             if way.get("geometry")]
    with open(path, "w") as file:
        json.dump(lines, file)
    return lines


def report_area(area: str, data_dir: str) -> dict:
    to_rd = pyproj.Transformer.from_crs("EPSG:4326", CRS, always_xy=True)
    project = lambda g: shapely.transform(g, lambda xy: np.column_stack(to_rd.transform(xy[:, 0], xy[:, 1])))
    bbox = shapely.box(*to_rd.transform_bounds(*AREAS[area]))
    with open(f"{area_dir(area, data_dir)}/{area}_bgt.pkl", "rb") as file:
        features = pickle.load(file)["wegdeel"]
    geoms = project(shapely.from_geojson([json.dumps(f["geometry"]) for f in features]))
    geoms = shapely.intersection(geoms, bbox)
    functions = np.array([f["properties"]["functie"] or "-" for f in features])

    areas = shapely.area(geoms)
    shares = {fn: float(areas[functions == fn].sum() / areas.sum()) for fn in np.unique(functions)}

    lines = [shapely.LineString(line) for line in bike_streets(area, area_dir(area, data_dir)) if len(line) > 1]
    lines = shapely.intersection(project(np.array(lines, dtype=object)), bbox) if lines else np.array([])
    total = float(shapely.length(lines).sum()) if len(lines) else 0.0
    under = {}
    if total:
        tree = shapely.STRtree(geoms)
        for line in lines:
            for i in tree.query(line, predicate="intersects"):
                under[functions[i]] = under.get(functions[i], 0.0) + shapely.length(shapely.intersection(line, geoms[i]))
    return {"shares": shares, "bike_street_m": total, "under_bike_streets": under}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("areas", nargs="*", default=list(AREAS), help="areas from areas.py (default: all)")
    parser.add_argument("--data-dir", default="data")
    parser.add_argument("--out", default="results/label_consistency.md")
    args = parser.parse_args()

    reports = {area: report_area(area, args.data_dir) for area in args.areas}
    functions = sorted({fn for r in reports.values() for fn in r["shares"]},
                       key=lambda fn: -sum(r["shares"].get(fn, 0) for r in reports.values()))

    out = ["# BGT label consistency between areas", "",
           "Generated by `label_report.py`.", "",
           "## Share of road surface (wegdeel area) per BGT function", "",
           "| function | " + " | ".join(reports) + " |", "|---|" + "---|" * len(reports)]
    for fn in functions:
        out.append(f"| {fn} | " + " | ".join(f"{r['shares'].get(fn, 0):.1%}" for r in reports.values()) + " |")
    out += ["", "## Fietsstraten (OSM) and the BGT function under them", "",
            "Length of OSM fietsstraat centreline inside the area, and how much of it runs over each BGT function.",
            "Lines along a polygon edge count for both sides, so shares can add up to over 100%.", "",
            "| area | fietsstraat length | BGT function under it |", "|---|---|---|"]
    for area, r in reports.items():
        under = ", ".join(f"{fn} {m / r['bike_street_m']:.0%}" for fn, m in
                          sorted(r["under_bike_streets"].items(), key=lambda kv: -kv[1]) if m / r["bike_street_m"] >= 0.02)
        out.append(f"| {area} | {r['bike_street_m'] / 1000:.1f} km | {under or '-'} |")
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as file:
        file.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
